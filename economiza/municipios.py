NOMES_MUNICIPIOS: list[str] = sorted(MUNICIPIOS_AL)


def normalizar(texto: str | None) -> str:
    """Maiúsculas, sem acentos e sem espaços extras (ex.: ' Maceió ' -> 'MACEIO')."""
    if not isinstance(texto, str):
        return ""
    return " ".join(unidecode.unidecode(texto).upper().split())


def codigo_ibge(nome_municipio: str) -> int:
    """Retorna o código IBGE de um município alagoano.

    Levanta ``ValueError`` se o nome não corresponder a nenhum município, em vez
    de mandar ``None`` para a API (o que gerava uma consulta inválida).
    """
    codigo = MUNICIPIOS_AL.get(normalizar(nome_municipio))
    if codigo is None:
        raise ValueError(f"Município não encontrado em Alagoas: {nome_municipio!r}")
    return codigo
